"""Writes values-<lang>/strings.xml for the Android app from desktop's locales and manual.py."""
import json
import os
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(__file__))
from manual import LANGS, PLURALS, STRINGS  # noqa: E402

DESKTOP = os.path.expanduser("~/workspace/LyricsAdapter/src/i18n/locales")
RES = os.path.expanduser("~/workspace/LyricsAdapter-Android/app/src/main/res")
SKIP = {"app_name", "wall_tile_label"}


def flat(tree, prefix=""):
    out = {}
    for key, value in tree.items():
        if isinstance(value, dict):
            out.update(flat(value, prefix + key + "."))
        else:
            out[prefix + key] = value
    return out


def escape(text):
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def main():
    desktop_zh = flat(json.load(open(os.path.join(DESKTOP, "zh.json"), encoding="utf-8")))
    by_value = {}
    for key, value in desktop_zh.items():
        by_value.setdefault(value, key)
    source = ET.parse(os.path.join(RES, "values", "strings.xml")).getroot()
    for index, lang in enumerate(LANGS):
        desktop = flat(json.load(open(os.path.join(DESKTOP, f"{lang}.json"), encoding="utf-8")))
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/i18n/generate.py from desktop's locales and tools/i18n/manual.py; edit those, not this file. -->",
                 "<resources>"]
        missing = []
        for element in source:
            name = element.get("name")
            if name in SKIP or element.get("translatable") == "false":
                continue
            if element.tag == "plurals":
                forms = PLURALS[name][index]
                lines.append(f'    <plurals name="{name}">')
                lines += [f'        <item quantity="{quantity}">{escape(text)}</item>' for quantity, text in forms.items()]
                lines.append("    </plurals>")
                continue
            if name in STRINGS:
                text = STRINGS[name][index]
            else:
                key = by_value.get(element.text or "")
                text = desktop.get(key) if key else None
                if text is None or "{{" in text:
                    missing.append(name)
                    continue
            lines.append(f'    <string name="{name}">{escape(text)}</string>')
        lines.append("</resources>")
        directory = os.path.join(RES, f"values-{lang}")
        os.makedirs(directory, exist_ok=True)
        with open(os.path.join(directory, "strings.xml"), "w", encoding="utf-8") as out:
            out.write("\n".join(lines) + "\n")
        print(lang, "missing:", missing)


main()
